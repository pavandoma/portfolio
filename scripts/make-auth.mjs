#!/usr/bin/env node
/**
 * Create the passphrase file for the learning log.
 *
 *   node scripts/make-auth.mjs
 *
 * Prompts for a passphrase (not echoed), then writes `auth.php` — a salted
 * PBKDF2 hash, not the passphrase — into ./portfolio-data/ (git-ignored).
 * Upload that one file to the server's `portfolio-data/` folder, which sits
 * next to public_html and is never served over the web.
 *
 * The passphrase goes into the learning page's "Edit" box. It only has to be
 * typed on a device you want to be able to tick things from.
 */

import { pbkdf2Sync, randomBytes } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROUNDS = 200000; // must match PBKDF2_ROUNDS in public/api/progress.php
const MIN_LENGTH = 12;

function readHidden(prompt) {
  return new Promise((resolve) => {
    process.stdout.write(prompt);
    const stdin = process.stdin;
    let value = "";
    if (stdin.isTTY) stdin.setRawMode(true);
    stdin.resume();
    stdin.setEncoding("utf8");
    const onData = (chunk) => {
      for (const ch of chunk) {
        if (ch === "\r" || ch === "\n" || ch === "\u0004") {
          if (stdin.isTTY) stdin.setRawMode(false);
          stdin.pause();
          stdin.off("data", onData);
          process.stdout.write("\n");
          resolve(value);
          return;
        }
        if (ch === "\u0003") process.exit(130);
        if (ch === "\u007f" || ch === "\b") value = value.slice(0, -1);
        else value += ch;
      }
    };
    stdin.on("data", onData);
  });
}

const first = await readHidden(`Passphrase (at least ${MIN_LENGTH} characters): `);
if (first.length < MIN_LENGTH) {
  console.error(`Too short: use at least ${MIN_LENGTH} characters. A few random words is fine.`);
  process.exit(1);
}
const second = await readHidden("Again: ");
if (first !== second) {
  console.error("Those did not match. Nothing was written.");
  process.exit(1);
}

const salt = randomBytes(16).toString("hex");
const hash = pbkdf2Sync(first, salt, ROUNDS, 32, "sha256").toString("hex");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "portfolio-data");
mkdirSync(outDir, { recursive: true });
const file = join(outDir, "auth.php");
writeFileSync(
  file,
  `<?php\n// Generated by scripts/make-auth.mjs. Holds a hash, never the passphrase.\nreturn ['salt' => '${salt}', 'hash' => '${hash}', 'rounds' => ${ROUNDS}];\n`,
  { mode: 0o600 },
);
console.log(`Wrote ${file}`);
console.log("Upload it to the server's portfolio-data/ folder (next to public_html).");
